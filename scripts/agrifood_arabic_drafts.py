def validate_local_drafts(record_ids: set[str]) -> None:
    """Fail closed if the local Arabic source is incomplete or has extra IDs."""

    if set(ARABIC_DRAFTS) != record_ids:
        missing = sorted(record_ids - set(ARABIC_DRAFTS))
        extra = sorted(set(ARABIC_DRAFTS) - record_ids)
        raise ValueError(f"Arabic draft ID mismatch; missing={missing}, extra={extra}")
    for record_id, fields in ARABIC_DRAFTS.items():
        if set(fields) != REQUIRED_ARABIC_FIELDS:
            raise ValueError(f"Arabic fields are incomplete for {record_id}")
        if any(not value.strip() for value in fields.values()):
            raise ValueError(f"Arabic text is empty for {record_id}")
